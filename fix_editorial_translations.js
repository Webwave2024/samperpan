const files = require('fs').readdirSync(messagesDir).filter(f => f.endsWith('.json'));

files.forEach(file => {
  const lang = file.replace('.json', '');
  const filePath = require('path').join(messagesDir, file);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  // Use language-specific editorial, fall back to English
  data.editorial = editorialByLang[lang] || editorialByLang.en;

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2));
  console.log(`Updated editorial translations for ${lang}`);
});
